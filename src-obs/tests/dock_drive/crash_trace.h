// ドックを操作するテスト (dock_drive.exe) がクラッシュしたときに、クラッシュした場所の呼び出し履歴を標準エラー出力に
// 書く (SetUnhandledExceptionFilter と dbghelp)。製品とテストのどちらのコードでクラッシュしたかを、その実行の出力
// だけで分けるためである。クラッシュは長い実行の中でまれにしか起きないので、デバッガーの下で再現を待たずに、その場で
// 書き残す。ダンプのファイルではなくテキストで書くのは、出力のログにそのまま残るためである。

#pragma once

namespace cordmux::dock_drive {

// クラッシュしたときの処理 (未処理例外フィルター) を登録する。main の最初に 1 回だけ呼ぶ。
void install_crash_trace();

// クラッシュする直前の記録 (最後の 512 件) に 1 行を加える。クラッシュしたときに、呼び出し履歴の後に古い順に書く。
// 入力の 1 つずつと、ウィジェットへの Enter と Leave のイベント (受けたウィジェットのアドレスと型) を残し、
// クラッシュした所で使われたウィジェットが既に破棄されていたかを分けられるようにする。text は 159 バイトまでで、
// 超えた分は切り捨てる。ロックを取らないので、UI スレッドからだけ呼ぶ。
void crash_note(const char *text);

} // namespace cordmux::dock_drive
