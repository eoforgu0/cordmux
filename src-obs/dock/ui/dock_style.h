// ドックと cordmux のダイアログの見た目の値 (倍率、余白、枠線の太さ、折り返しのしきい値)。
// 見た目の候補を分岐ではなく既定の値を持つフィールドとして 1 か所に置き、既定を変えるときはここだけを修正する。
// プレビューツール (ui_preview) は、この値をオプション (--first-line-scale、--l1-border、--tier-icons) で変えて
// 候補を並べて描画する。Qt に依存しないので、単体テストから直接読み込める。
// 色は持たない。色はテーマから読み、状態ごとの色も使わない (メッセージのレベル 1 のパネルだけが色を持つ)。

#pragma once

namespace cordmux::dock::ui {

// メッセージのレベルのアイコンのセット。ThemeMono は cordmux が描く 1 色のアイコンで、本文の色で描く (メッセージの
// レベル 1 だけは白か黒)。WindowsStandard は Windows の標準の色付きのアイコンで、見た目を比べるためだけに残す。
// 標準のアイコンの色の部分と背景のコントラスト比が、テーマによって 3:1 に届かないので、既定にしない。
enum class TierIconSet { ThemeMono, WindowsStandard };

struct DockStyle {
	// ドックの 1 行目のフォントの倍率 (OBS の本文に対する倍率)。OBS のテーマの文字の大きさの段 (Yami.obt の --font_base 1、
	// --font_large 1.1、--font_xlarge 1.5、--font_heading 2.5) から選ぶ。1 行目に出うる見出しと状態の文 (プレビューツールの
	// 場面の 64 通り) が、初めてドックを表示するときの幅 (26 em、Yami) で省かれずに全文が入る割合は、1.5 で日本語 52%・英語 45%、
	// 1.1 で 80%・70%、1 で 88%・80% で、1 がいちばん高い。そのため本文と同じ 1 にする。見出し (メッセージ) は太字で、平常の
	// 状態の文と見分ける (TypeLevel::FirstLineHeading)。1 行目の高さはボタンの高さで決まるので、倍率を下げても変わらない。
	double first_line_scale = 1.0;

	// メッセージのレベル 1 のパネルの外周の枠線の太さ (px)。負の値なら、パネルと背景のコントラスト比が
	// l1_border_contrast_min に届かないときだけ、l1_border_auto_px の太さで描く。0 以上の値は、コントラスト比に
	// よらずその太さにする (見た目を比べるため)。枠線は、パネルが背景から見分けにくいテーマで、パネルの位置を
	// 視野の端でも分かるようにするために描く。コントラスト比が足りるテーマで描くと、狭いドックの上端が重く見える。
	int l1_border_px = -1;
	// コントラスト比で決めるときの枠線の太さと、描くかどうかのしきい値。3:1 は WCAG 1.4.11 の値を、外形が
	// 見えるかの目安として借りたもので、規格に適合させるための値ではない。
	int l1_border_auto_px = 2;
	double l1_border_contrast_min = 3.0;

	TierIconSet tier_icon_set = TierIconSet::ThemeMono;

	// cordmux がレイアウトに置く余白 (小、大) と、別のまとまりの間隔。ウィジェットの内側の余白は OBS の
	// テーマに任せる。まとまりの間隔をまとまりの中より広くするのは、メッセージの行が参加者の一覧の 1 行目に
	// 見えないようにするためと、表の隣どうしの列の見出しが続けて読まれないようにするためである。
	double spacing_small_em = 0.25;
	double spacing_large_em = 0.5;
	double group_gap_em = 0.75;

	// 見出しの段と説明の文と、意味やまとまりが違う部分の間の余白 (em)。表示タブの大見出し (枠、名前ラベル、話している人の強調、
	// ダミー映像) と中見出し (背景、名前、輪郭 など)、状態タブの見出しに使う。階層は太さと余白で作り、色の弱さでは作らない
	// (見出しはどの段も本文の色の太字にする。暗い背景で見出しを補足の色にすると、項目の名前より目を引かず、押せない項目の
	// 名前とも同じ色になるため)。大きさを変えるのは大見出しだけで、OBS のテーマの段 --font_large と同じ 1.1 倍にする (狭い
	// ドックで段を大きさで分けすぎない)。値はプレビューツールのオプション (--heading-scale、--heading-space、--note-below、
	// --section-gap) で変えて比べられる。
	//
	// 中見出しは、上の余白を 1 em 以上、かつ下の余白の 3 倍以上にし、前のまとまりより自分の中身の近くに置く (近接の原則。
	// 罫線を引かないので、余白だけで、見出しがどの項目の見出しかが分かるようにする)。比べるのは見た目の余白 (前の部品の下端
	// から見出しの字の上端まで と、字の下端から次の部品の上端まで) である。見た目の余白には、字の上下の空き (2-4 px) と部品の
	// 中の余白 (チェックボックスの印の上下 3-4 px、コンボボックスと数の入力欄の枠の外 2 px) が足されるので、レイアウトの値の
	// 比とは違う。中見出しの下はレイアウトでは行の間 (0.25 em) だけにしても、見た目では 1 em が 13.3 px のとき 6-11 px ある。
	// そのため上は 2.25 em にして、見た目で 33 px 以上にする (前の部品の種類による違いは 4 px 以内)。
	// 次の 2 つは、この 3 倍の対象にしない。
	//   - 大見出しのすぐ後の中見出し (「名前ラベル」の後の「名前」)。前にあるのは自分を含む組の見出しで、前のまとまりの
	//     項目ではないので、どちらの項目の見出しかを取り違えない。上を 3 倍にすると、大見出しだけが罫線の近くに離れて残る。
	//     上は大見出しの下の余白だけにする。
	//   - 大見出し。上のはっきりした罫線が組を分けるので、見出しを中身に寄せなくても、どの組の見出しかを取り違えない。
	//     罫線から字までを見た目で 1 em 以上にする (group_heading_above を 1 em にして、見た目で 16-17 px。0.75 em では、
	//     濁点のある字 (「ダミー映像」) で 13 px になり、1 em に届かなかった)。
	double group_heading_scale = 1.1;
	double group_rule_above_em = 1.0;     // 前の行の下から、大見出しの上のはっきりした罫線まで
	double group_heading_above_em = 1.0;  // 罫線から大見出しの文字まで
	double group_heading_below_em = 0.5;  // 大見出しの下から次の行まで
	double sub_heading_above_em = 2.25;   // 前の行の下から中見出しまで (罫線は引かない)
	double sub_heading_below_em = 0.25;   // 中見出しの下から次の行まで
	// 状態タブの見出しの上 (前の行の下から見出しまで。見出しの下は中見出しと同じ sub_heading_below_em)。表示タブの中見出しより
	// 狭い 1 em にする。配信中のドックは縦の場所が限られ、状態タブは見出しが 4 つ並ぶので、2.25 em にすると、見出しごとに
	// 1.25 em ずつ、表や [映像のバッファ] が下に押されるため (見出しのすぐ下は 1 行の値か表)。見た目は、1 em が 13.3 px のとき
	// 上 18-21 px、下 6-9 px で、上は下の 2.1-2.6 倍 (Vesktop の見出しだけ 3.2 倍) になり、表示タブの中見出しの 3 倍には届かない
	// (3 倍以上にするには 1.75 em が要る)。
	double status_heading_above_em = 1.0;
	// 説明の文 (項目の名前でも値でもない文。補足の色) の下から次の行まで。上は行の間 (spacing_small_em) だけにして、説明する
	// 項目に寄せる。
	double note_below_em = 0.5;
	// 意味やまとまりが違う部分の間 (見出しのない切れ目)。1 em にする (見出しがないので、見出しを中身に寄せるための中見出しの
	// 上の余白ほどは空けない)。同じまとまりの項目の間は spacing_small_em のまま。
	double section_gap_em = 1.0;

	// 一覧の行の高さの下限。WCAG 2.5.8 の 24 x 24 CSS px による。Qt のデバイスに依存しないピクセルを
	// CSS px と同じ大きさとして扱う。
	int row_min_height_px = 24;
	// 参加者の一覧の行で名前に残す最小の幅。ドックが狭くなっても、名前はこの幅まで残す。
	double name_floor_em = 4.0;

	// 段落の 1 行の幅の上限と、ダイアログの幅の上限。上限がないと、広げたドックやダイアログで 1 行が 100 字を
	// 超える。40 em (全角で 40 字) は日本語の本の 1 行の字数の慣行からの値で、測って決めたものではない。
	double paragraph_max_em = 40.0;
	double dialog_max_em = 45.0;

	// フォーカスリング。押せる範囲から 1 px 空けて、2 px の線で囲む。
	int focus_ring_px = 2;
	int focus_ring_gap_px = 1;
	// フォーカスリングがメッセージのレベル 1 のパネルの枠線に接すると、リングの外側のコントラスト比が 1 に近くなる。
	// これはドックの側で、パネルの枠線の内側に余白を取って避ける (dock/notice_list.cpp の
	// l1_ring_clearance_px)。リングの外側を背景の色の線で囲む方法は使わない。バー、カード、パネルの上で
	// リングの外に 1 px の線が見え、場所によってリングの見た目が変わるため。

	// ダイアログの主文のフォントの倍率 (OBS の本文に対する倍率)。Windows のタスクダイアログ
	// (TASKDIALOGCONFIG の pszMainInstruction) と同じく、主文を補足より大きくする。1.5 はドックの 1 行目と同じ
	// 倍率である。0 にすると OBS のテーマのクラス text-large (本文の 1.1 倍) に任せる。0 は見た目を比べるための
	// 値で、既定にはしない。1.1 倍の普通の太さは、cordmux が使う 5 種類のテキストの見た目 (1.5 em、1.1 em の太字、1 em の
	// 太字、1 em、1 em の弱いテキスト。type_scale.h) のどれとも違う 6 種類目になるため。
	double dialog_main_scale = 1.5;
	// dialog_main_scale が 0 で、テーマが text-large を持たず主文が補足と同じ大きさになるときだけ適用する倍率。
	// 1.1 は OBS のテーマの --font_large と同じ倍率である。
	double dialog_main_fallback_scale = 1.1;
	// 主文が 1 行に入らずに 2 行になるとき、この文字列のどれかの文字の直後で折り返す。Qt の折り返しでは、
	// 「...同梱のものに切」と「り替えますか？」のように語の途中で折れることがあるため。nullptr か空なら Qt の
	// 折り返しのままにする。既定は読点「、」だけである。
	const char16_t *dialog_main_break_after = u"、";

	// 本文を折り返したとき、最後の行に残す最小の文字数 (書記素クラスターで数える)。最後の行が句読点を含めて
	// 2 文字以下になると読みにくいので、これより少なければ、折り返す幅を狭めて前の行から文字を移す。
	int min_last_line_graphemes = 3;
	// 最後の行の長さの下限 (折り返す幅に対する比)。文字数の下限を満たしても、1 語だけが最後の行に残る形
	// (「さい。」や "folder.") を避ける。0 なら文字数だけを見る。
	double min_last_line_ratio = 0.25;
	// 最後の行のために折り返す幅を狭めるときの下限 (元の幅に対する比)。
	double wrap_narrow_floor_ratio = 0.75;
};

} // namespace cordmux::dock::ui
